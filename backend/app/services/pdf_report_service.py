import io
from decimal import Decimal
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable

def generate_report_pdf(report_title: str, date_range_label: str, summary_data: dict, table_rows: list, headers: list, col_widths: list = None) -> bytes:
    """
    Generates an executive PDF report with supermarket headers, summary statistics, and itemized data tables.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=16,
        leading=20,
        alignment=1,
        textColor=colors.HexColor("#0f172a")
    )

    sub_style = ParagraphStyle(
        'DocSub',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        alignment=1,
        textColor=colors.HexColor("#475569")
    )

    bold_label = ParagraphStyle(
        'BoldLabel',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#1e293b")
    )

    norm_val = ParagraphStyle(
        'NormVal',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#334155")
    )

    story = []

    # Store Header
    story.append(Paragraph("SMARTRETAIL HYPERMARKET - AUDIT & REPORTING SUITE", title_style))
    story.append(Paragraph(f"Report: <b>{report_title}</b> • Period: <b>{date_range_label}</b>", sub_style))
    story.append(Paragraph(f"Generated On: {datetime.now().strftime('%d-%b-%Y %I:%M %p')} • Branch #104 Indiranagar", sub_style))
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0f766e"), spaceAfter=10))

    # Summary KPI Box (if provided)
    if summary_data:
        kpi_cells = []
        row = []
        for k, v in summary_data.items():
            cell_p = Paragraph(f"<b>{k}:</b><br/>{v}", norm_val)
            row.append(cell_p)
            if len(row) == 4:
                kpi_cells.append(row)
                row = []
        if row:
            while len(row) < 4:
                row.append(Paragraph("", norm_val))
            kpi_cells.append(row)

        kpi_table = Table(kpi_cells, colWidths=[135, 135, 135, 135])
        kpi_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ('INNERGRID', (0, 0), (-1, -1), 0.25, colors.HexColor("#e2e8f0")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(kpi_table)
        story.append(Spacer(1, 10))

    # Main Data Table
    table_data = []
    header_cells = [Paragraph(f"<b>{h}</b>", bold_label) for h in headers]
    table_data.append(header_cells)

    for r in table_rows:
        row_cells = []
        for cell in r:
            row_cells.append(Paragraph(str(cell), norm_val))
        table_data.append(row_cells)

    if not col_widths:
        w = 540 / len(headers)
        col_widths = [w] * len(headers)

    data_table = Table(table_data, colWidths=col_widths)
    data_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#0f766e")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 5),
        ('RIGHTPADDING', (0, 0), (-1, -1), 5),
    ]))
    story.append(data_table)
    story.append(Spacer(1, 14))

    # Footer note
    footer_text = Paragraph(
        "<i>Confidential Supermarket Financial & Inventory Report. System-generated by SmartRetail AI Analytics Engine.</i>",
        sub_style
    )
    story.append(footer_text)

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()

